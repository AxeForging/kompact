/**
 * One real session, as a timeline the page can play back.
 *
 * Section 03 shows nine calls being decided. It does not show the thing a reader
 * actually has to understand: that a session fills with tool output, that the
 * engine fires at a threshold, and that what happens then is a sweep in score
 * order which stops once the budget is met. That is the product, and the page
 * has only ever asserted it.
 *
 * So: take one session out of the committed corpus, in order, and emit what it
 * takes to replay it — the tool, the output size, the score, and the decision
 * the shipped policy makes when compaction fires. No text of any kind is
 * emitted, only shapes and numbers, and the source is the scrubbed fixture that
 * already ships, so this publishes nothing a transcript would not.
 *
 * Writes `docs/timeline-data.js`. Run: bun eval/timeline.ts
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCorpus, rowKey } from './corpus.js';
import { outOfFoldScores } from './oof.js';
import { DEFAULT_OPTIONS, decideAll, freedBy } from '../src/compact.js';
import type { CallAnswer, ToolCall } from '../src/index.js';
import type { LabelRow } from './extract-labels.js';

const here = dirname(fileURLToPath(import.meta.url));
const { rows, from } = loadCorpus(here, { fixtureOnly: true });
const { result: resultScore, call: callScore } = outOfFoldScores(here, rows);

/** `compactAtPercent`: the share of the window in use when the engine fires. */
const AT = 60;

/**
 * Which session to play. Not hand-picked: the median-length session among those
 * long enough to show a sweep, so the reader watches a typical one rather than a
 * flattering one.
 */
const byName = new Map<string, LabelRow[]>();
for (const row of rows) {
  const list = byName.get(row.session) ?? [];
  list.push(row);
  byName.set(row.session, list);
}
const candidates = [...byName.entries()]
  .filter(([, list]) => list.length >= 25)
  .sort((a, b) => a[1].length - b[1].length);
if (candidates.length === 0) throw new Error('no session in the corpus is long enough to play');
const ordered = [...candidates[Math.floor(candidates.length / 2)]![1]]
  .sort((a, b) => a.result_index - b.result_index);

const total = ordered.reduce((sum, row) => sum + row.output_chars, 0);
let seen = 0;
let point = ordered.at(-1)!.result_index;
for (const row of ordered) {
  seen += row.output_chars;
  if (seen >= (AT / 100) * total) { point = row.result_index; break; }
}

// Only what exists when compaction fires is a candidate, exactly as in production.
const present = ordered.filter((row) => row.result_index <= point);
const calls: ToolCall[] = present.map((row) => ({
  id: rowKey(row), tool_use_id: rowKey(row), tool: row.tool, input: {},
  callIndex: 0, resultIndex: row.result_index, resultText: '', resultChars: row.output_chars,
  isError: row.is_error, pinned: false,
}));
const byId = new Map(calls.map((call) => [call.id, call]));
const answers = new Map<string, CallAnswer>(present.map((row) => [
  rowKey(row),
  { keepResult: resultScore.get(rowKey(row))!, keepCall: callScore.get(rowKey(row))! },
]));
const decisions = new Map(decideAll(calls, answers, DEFAULT_OPTIONS).map((d) => [d.id, d]));

const steps = ordered.map((row) => {
  const key = rowKey(row);
  const decision = decisions.get(key);
  return {
    tool: row.tool,
    chars: row.output_chars,
    // Present when compaction fires, so decided. The rest arrive afterwards.
    decided: decision !== undefined,
    keep: Number((resultScore.get(key) ?? 0).toFixed(3)),
    action: decision?.action ?? 'keep',
    reason: decision?.reason ?? 'arrived after the compaction point',
    // Whether it was ever quoted again, which is what a wrong drop costs.
    reusedLater: row.first_reuse_index > point ? 1 : 0,
    freed: decision ? freedBy(byId.get(key)!, decision.action, DEFAULT_OPTIONS.truncateHeadChars) : 0,
  };
});

const freed = steps.reduce((sum, s) => sum + s.freed, 0);
const presentChars = present.reduce((sum, row) => sum + row.output_chars, 0);
const data = {
  at: AT,
  floor: DEFAULT_OPTIONS.keepThreshold,
  budget: DEFAULT_OPTIONS.targetReduction,
  calls: ordered.length,
  presentAtCompaction: present.length,
  charsTotal: total,
  charsAtCompaction: presentChars,
  freed,
  dropped: steps.filter((s) => s.action === 'drop_call').length,
  truncated: steps.filter((s) => s.action === 'drop_result').length,
  steps,
};

const out = join(here, '..', 'docs', 'timeline-data.js');
writeFileSync(out, `/* Generated by eval/timeline.ts — do not edit. */\nwindow.TIMELINE = ${JSON.stringify(data)};\n`);
console.log(`wrote ${out} (${from})`);
console.log(`  ${data.calls} calls, ${data.presentAtCompaction} present when it fires at ${AT}%`);
console.log(`  ${data.truncated} truncated, ${data.dropped} dropped, ` +
  `${freed.toLocaleString('en-GB')} of ${presentChars.toLocaleString('en-GB')} chars freed ` +
  `(${((100 * freed) / presentChars).toFixed(1)}%)`);
